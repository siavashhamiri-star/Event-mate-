export function formatMoney(
  amountToman: number,
  currency: CurrencyCode,
  lang: LanguageCode,
  customRates?: Record<CurrencyCode, number>,
): string {
  const rate =
    customRates?.[currency] ?? CURRENCY_META[currency].defaultRateFromToman;
  const converted = amountToman * rate;

  if (currency === 'IRT') {
    const rounded = Math.round(converted);
    if (lang === 'FA' || lang === 'AR') {
      return `${rounded.toLocaleString('fa-IR')} تومان`;
    }
    return `${rounded.toLocaleString('en-US')} IRT`;
  }

  const formatted =
    converted >= 100
      ? Math.round(converted).toLocaleString('en-US')
      : converted.toFixed(2);

  if (currency === 'USD') return `$${formatted}`;
  if (currency === 'AED') return `${formatted} AED`;
  if (currency === 'TRY') return `₺${formatted}`;
  if (currency === 'RUB') return `${formatted} ₽`;
  return `${formatted} ${currency}`;
}

